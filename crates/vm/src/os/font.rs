/// Returns the 8x11 bitmap for character code `c`.
#[inline]
pub fn glyph(c: i16) -> &'static [u8; 11] {
    if (32..=126).contains(&c) {
        &FONT[(c - 32) as usize]
    } else {
        &FALLBACK_GLYPH
    }
}
